    private void refreshInventoryTable(String searchTerm) {
        javax.swing.table.DefaultTableModel model3 = (javax.swing.table.DefaultTableModel) jTable3.getModel();
        model3.setRowCount(0); // Clear the table before loading new search results
        
        CRUD_OP crud = new CRUD_OP();
        java.sql.ResultSet rs = crud.searchInventory(searchTerm);
          
        if (rs != null) {
            try {
                while (rs.next()) {
                    // Make sure your jTable3 columns match this order in the Design view!
                    model3.addRow(new Object[]{
                        rs.getInt("items_id"),
                        rs.getString("code"),
                        rs.getString("Item_name"), // This successfully displays the NAME!
                        rs.getDouble("price"),
                        rs.getString("Status")
                    });
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }
