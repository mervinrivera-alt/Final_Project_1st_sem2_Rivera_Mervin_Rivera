    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String categoryName = jTextField1.getText().trim();

        if (categoryName.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Category name cannot be empty!", "Input Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (isUpdateMode) {
            boolean success = CRUD_OP.updateCategory(updateCategoryId, categoryName);

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Category updated successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                isUpdateMode = false;
                updateCategoryId = -1;
                jButton1.setText("Add Category");
                jTextField1.setText("");
                jTextField2.setText("");
                CRUD_OP.readCategories(jTable1);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to update category.", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } else {
            boolean success = CRUD_OP.addCategory(categoryName);

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Category '" + categoryName + "' added successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                jTextField1.setText("");
                CRUD_OP.readCategories(jTable1);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to add category.", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

