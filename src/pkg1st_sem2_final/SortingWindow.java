    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String idText = jTextField3.getText().trim();

        if (idText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Category ID to delete.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int id = Integer.parseInt(idText);
            String categoryName = CRUD_OP.getCategoryName(id);

            if (categoryName == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Category ID does not exist!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            int confirm = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to permanently delete the category: " + categoryName + "?",
                    "Confirm Deletion",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                boolean success = CRUD_OP.deleteCategory(id);

                if (success) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Category '" + categoryName + "' deleted successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                    jTextField3.setText("");
                    CRUD_OP.readCategories(jTable1);

                    if (id == updateCategoryId) {
                        isUpdateMode = false;
                        updateCategoryId = -1;
                        jButton1.setText("Add Category");
                        jTextField1.setText("");
                        jTextField2.setText("");
                    }
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete this category. It may be linked to active inventory batches.", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid ID format. Please enter a valid number.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

