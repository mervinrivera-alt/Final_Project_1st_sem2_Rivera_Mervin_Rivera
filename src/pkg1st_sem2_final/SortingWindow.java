    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        try {
            if (jComboBox1.getSelectedItem() == null || jComboBox2.getSelectedItem() == null || jTextField9.getText().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill all form inputs.");
                return;
            }

            int batchId = Integer.parseInt(jComboBox1.getSelectedItem().toString());
            info.CategoryItem selectedCategory = (info.CategoryItem) jComboBox2.getSelectedItem();
            String itemName = jTextField9.getText();

            CRUD_OP crud = new CRUD_OP();
            String[] batchDetails = crud.getBatchDetails(batchId);

            if (batchDetails == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error fetching reference data.");
                return;
            }

            String arrivalDate = batchDetails[0];
            int quantity = Integer.parseInt(batchDetails[1]); // Pulled automatically from database

            boolean success;
            if (isUpdateMode) {
                success = crud.updateSortedBatch(currentEditingSortedId, selectedCategory.id, itemName, quantity, batchId, arrivalDate);
            } else {
                success = crud.addSortedBatch(selectedCategory.id, itemName, quantity, batchId, arrivalDate);
            }

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, isUpdateMode ? "Sorted record updated!" : "Batch sorted successfully!");

                isUpdateMode = false;
                currentEditingSortedId = -1;
                jTextField9.setText("");
                jTextField10.setText("");

                setupSortForm();       // Refreshes your ComboBoxes
                loadSortedTable3();    // <--- THIS IS THE LINE THAT REFRESHES YOUR JTABLE
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButton7ActionPerformed

