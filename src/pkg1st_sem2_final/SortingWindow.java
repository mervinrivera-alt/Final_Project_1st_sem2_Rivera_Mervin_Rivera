    public void loadDeliveryTable() {
        // 1. Get the table model and clear the old data
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable2.getModel();
        model.setRowCount(0);

        // 2. Create your CRUD object and call the fetch method
        CRUD_OP crud = new CRUD_OP();

        try (java.sql.ResultSet rs = crud.getAllDeliveries()) {

            // 3. Loop through the results and add them to jTable2
            if (rs != null) {
                while (rs.next()) {
                    int batchId = rs.getInt("Batch_id");
                    int crateId = rs.getInt("crate_id");
                    String date = rs.getString("Arrival_date");
                    int qty = rs.getInt("Quantities");

                    model.addRow(new Object[]{batchId, crateId, qty, date});
                }
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error updating table: " + e.getMessage());
        }
    }

