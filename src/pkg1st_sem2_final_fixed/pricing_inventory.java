    public void refreshPricingUI() {
        javax.swing.table.DefaultTableModel model1 = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        javax.swing.table.DefaultTableModel model2 = (javax.swing.table.DefaultTableModel) jTable2.getModel();
        model1.setRowCount(0);
        model2.setRowCount(0);
        jComboBox1.removeAllItems();

        try {
            Connection conn = DBConnection.getConnection();

            // 1. Load Unpriced Batches (jTable1 and jComboBox1)
            // We join sorted_batch and delivery_arrive to get the dates and crate IDs for the Smart Code
            // 1. Load Unpriced Batches (jTable1 and jComboBox1) using a safe LEFT JOIN
            String unpricedSql = "SELECT sb.sorted_id, sb.Item_name, sb.Quantities, da.Batch_id, da.crate_id, da.Arrival_date "
                    + "FROM 1st_sem2_final.sorted_batch sb "
                    + "LEFT JOIN 1st_sem2_final.delivery_arrive da ON sb.delivery_arrive_Batch_id = da.Batch_id "
                    + "WHERE NOT EXISTS (SELECT 1 FROM 1st_sem2_final.items i WHERE i.Sorted_batch_sorted_id = sb.sorted_id)";

            java.sql.PreparedStatement pstmt1 = conn.prepareStatement(unpricedSql);
            java.sql.ResultSet rs1 = pstmt1.executeQuery();

            while (rs1.next()) {
                // Add to jTable1 (Only Name and Quantity)
                System.out.println("Found unpriced item: " + rs1.getString("Item_name"));
                model1.addRow(new Object[]{rs1.getString("Item_name"), rs1.getInt("Quantities")});

                // Add to jComboBox1 (Using our helper class to store hidden data)
                ((javax.swing.JComboBox) jComboBox1).addItem(new BatchComboItem(
                        rs1.getInt("sorted_id"), rs1.getString("Item_name"),
                        rs1.getInt("Batch_id"), rs1.getInt("crate_id"), rs1.getDate("Arrival_date")
                ));

            }

            // 2. Load Priced Items (jTable2) - Displaying Name instead of ID
            String pricedSql = "SELECT i.items_id, i.code, sb.Item_name, i.price, i.Status "
                    + "FROM 1st_sem2_final.items i "
                    + "JOIN 1st_sem2_final.sorted_batch sb ON i.Sorted_batch_sorted_id = sb.sorted_id";

            java.sql.PreparedStatement pstmt2 = conn.prepareStatement(pricedSql);
            java.sql.ResultSet rs2 = pstmt2.executeQuery();

            while (rs2.next()) {
                model2.addRow(new Object[]{
                    rs2.getInt("items_id"), rs2.getString("code"),
                    rs2.getString("Item_name"), rs2.getDouble("price"), rs2.getString("Status")
                });
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
        }
    }

