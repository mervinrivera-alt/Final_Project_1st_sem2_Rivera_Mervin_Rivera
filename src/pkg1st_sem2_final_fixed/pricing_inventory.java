    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (jTextField1.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Warning: Price cannot be empty!");
            return;
        }

        double inputPrice;
        try {
            inputPrice = Double.parseDouble(jTextField1.getText().trim());
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Warning: Price must be a valid number!");
            return;
        }

        try {
            java.sql.Connection conn = DBConnection.getConnection();

            // 2. Determine Mode based on JComboBox being locked or unlocked
            if (jComboBox1.isEnabled()) {

                if (jComboBox1.getSelectedItem() == null) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Warning: No batch selected to price!");
                    return;
                }

                // Get hidden data from the combobox item
                BatchComboItem selectedBatch = (BatchComboItem) jComboBox1.getSelectedItem();

                // Format the Smart Code: Batch_id - MMDDYY - crate_id
                java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("MMddyy");
                String formattedDate = sdf.format(selectedBatch.arrivalDate);
                String smartCode = selectedBatch.batchId + "-" + formattedDate + "-" + selectedBatch.crateId;

                // Pack the data into your ItemsInfo Model!
                // Note: itemsId is set to 0 because the database will Auto-Increment it.
                ItemsInfo newItem = new ItemsInfo(0, smartCode, selectedBatch.sortedId, inputPrice, "Available");

                // Insert into Database
                String insertSql = "INSERT INTO 1st_sem2_final.items (code, Sorted_batch_sorted_id, price, Status) VALUES (?, ?, ?, ?)";
                java.sql.PreparedStatement pstmt = conn.prepareStatement(insertSql);
                pstmt.setString(1, newItem.getCode());
                pstmt.setInt(2, newItem.getSortedBatchId());
                pstmt.setDouble(3, newItem.getPrice());
                pstmt.setString(4, newItem.getStatus());

                pstmt.executeUpdate();
                javax.swing.JOptionPane.showMessageDialog(this, "Successfully Priced! Smart Code Generated: " + smartCode);

            } else {

                int updateId = Integer.parseInt(jTextField2.getText().trim());

                String updateSql = "UPDATE 1st_sem2_final.items SET price = ? WHERE items_id = ?";
                java.sql.PreparedStatement pstmt = conn.prepareStatement(updateSql);
                pstmt.setDouble(1, inputPrice);
                pstmt.setInt(2, updateId);

                pstmt.executeUpdate();

                // Unlock UI and clear fields after successful update
                jComboBox1.setEnabled(true);
                jTextField2.setText("");
                javax.swing.JOptionPane.showMessageDialog(this, "Price Updated Successfully!");
            }

            // 3. Reset Fields and Refresh Tables
            jTextField1.setText("");
            refreshPricingUI(); // Reloads both tables to reflect the new state

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            int updateId = Integer.parseInt(jTextField2.getText().trim());
            java.sql.Connection conn = DBConnection.getConnection();

            // Check if item exists and fetch its current data 
            String checkSql = "SELECT i.price, sb.Item_name "
                    + "FROM 1st_sem2_final.items i JOIN 1st_sem2_final.sorted_batch sb ON i.Sorted_batch_sorted_id = sb.sorted_id "
                    + "WHERE i.items_id = ?";

            java.sql.PreparedStatement pstmt = conn.prepareStatement(checkSql);
            pstmt.setInt(1, updateId);
            java.sql.ResultSet rs = pstmt.executeQuery();

            if (rs.next()) {
                // Success! Item found. Lock the UI into "Update Mode"
                jComboBox1.removeAllItems(); // Clear it
                jComboBox1.addItem(rs.getString("Item_name")); // Just show the raw name
                jComboBox1.setEnabled(false); // Lock the combobox!

                jTextField1.setText(String.valueOf(rs.getDouble("price"))); // Show old price
                javax.swing.JOptionPane.showMessageDialog(this, "Item found. Enter new price and click Save/Update.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Warning: Item ID not found in database.");
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Warning: Please enter a valid numerical Item ID.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

