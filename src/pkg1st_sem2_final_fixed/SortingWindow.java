    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        try {
            // 1. Basic validation: Make sure a Special ID and Category are selected
            if (jComboBox1.getSelectedItem() == null || jComboBox2.getSelectedItem() == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please select a Special ID and a Category.");
                return;
            }
            if (jTextField9.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please enter an Item Name.");
                return;
            }

            // 2. Get the Special ID directly from jComboBox1 (No splitting needed!)
            String selectedIdText = jComboBox1.getSelectedItem().toString().trim();
            int specialId = Integer.parseInt(selectedIdText);

            // 3. Extract the Category ID and Item Name
            info.CategoryItem selectedCategory = (info.CategoryItem) jComboBox2.getSelectedItem();
            int categoryId = selectedCategory.id;
            String itemName = jTextField9.getText().trim();

            // 4. Fetch the existing batch records from the database using the Special ID
            // so we don't overwrite or lose the original quantities, batch IDs, and dates!
            int batchId = 0;
            String arrivalDate = "";
            int quantity = 0;

            String fetchSql = "SELECT delivery_arrive_Batch_id, delivery_arrive_Arrival_date, Quantities "
            + "FROM 1st_sem2_final.sorted_batch WHERE sorted_id = ?";

            try (java.sql.Connection conn = DBConnection.getConnection();
                java.sql.PreparedStatement pstmt = conn.prepareStatement(fetchSql)) {

                pstmt.setInt(1, specialId);
                try (java.sql.ResultSet rs = pstmt.executeQuery()) {
                    if (rs.next()) {
                        batchId = rs.getInt("delivery_arrive_Batch_id");
                        arrivalDate = rs.getString("delivery_arrive_Arrival_date");
                        quantity = rs.getInt("Quantities");
                    } else {
                        javax.swing.JOptionPane.showMessageDialog(this, "Error: Special ID " + specialId + " not found in database.");
                        return;
                    }
                }
            }

            // 5. Call your CRUD operation to update the database
            CRUD_OP crud = new CRUD_OP();
            boolean success = crud.updateSortedBatch(specialId, categoryId, itemName, quantity, batchId, arrivalDate);

            // 6. Success actions and UI refresh
            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Sorted record updated successfully!");

                // Reset text fields back to empty
                jTextField9.setText("");
                if (jTextField11 != null) {
                    jTextField11.setText("");
                }

                // Refresh your interface structures
                setupSortForm();
                loadSortedTable3();
                loadDeliveryTable();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database update failed. Check your connection.");
            }

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "The Special ID selected is not a valid number.");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error processing update: " + ex.getMessage());
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButton7ActionPerformed

