    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        try {
            // 1. Validate fields are filled
            if (jTextField4.getText().isEmpty() || jTextField5.getText().isEmpty() || jTextField6.getText().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill in Batch ID, Crate ID, and Quantity.");
                return;
            }

            // 2. Grab the data
            int batchId = Integer.parseInt(jTextField4.getText());
            int crateId = Integer.parseInt(jTextField5.getText());
            int quantity = Integer.parseInt(jTextField6.getText());

            CRUD_OP crud = new CRUD_OP();
            boolean success = false;

            // 3. THE TWO-WAY CHECK: Does this Batch ID already exist?
            if (crud.getDeliveryInfo(batchId) != null) {
                // IT EXISTS: Run the Update Method
                success = crud.updateDelivery(batchId, crateId, quantity);
                if (success) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Existing Delivery UPDATED successfully!");
                }
            } else {
                // IT DOES NOT EXIST: Run the Insert Method
                success = crud.addDelivery(batchId, crateId, quantity); // Ensure this method uses the automatic date!
                if (success) {
                    javax.swing.JOptionPane.showMessageDialog(this, "New Delivery SAVED successfully!");
                }
            }

            // 4. Clean up the form after a successful save/update
            if (success) {
                jTextField4.setText("");
                jTextField5.setText("");
                jTextField6.setText("");
                jTextField7.setText(""); // Clear the search box
                jTextField4.setEditable(true); // Unlock the Batch ID field again
                loadDeliveryTable();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Action failed.");
            }

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Make sure all IDs and Quantities are numbers.");
        }
    }//GEN-LAST:event_jButton4ActionPerformed

