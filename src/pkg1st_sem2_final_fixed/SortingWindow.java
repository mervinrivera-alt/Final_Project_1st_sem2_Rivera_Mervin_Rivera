    public void loadDeliveryTable() {
        String[] columnNames = {"Batch ID", "Crate ID", "Arrival Date", "Quantity"};
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(columnNames, 0);
    
    // 2. Select deliveries ONLY IF their Batch_id is NOT in the sorted_batch table
    String sql = "SELECT Batch_id, crate_id, Arrival_date, Quantities " +
                 "FROM 1st_sem2_final.delivery_arrive " +
                 "WHERE Batch_id NOT IN (SELECT delivery_arrive_Batch_id FROM 1st_sem2_final.sorted_batch)";
    
    try (java.sql.Connection conn = DBConnection.getConnection()) {
        if (conn != null) {
            try (java.sql.PreparedStatement pstmt = conn.prepareStatement(sql);
                 java.sql.ResultSet rs = pstmt.executeQuery()) {
                
                // 3. Loop through the remaining unsorted rows and add them to the model
                while (rs.next()) {
                    Object[] row = new Object[] {
                        rs.getInt("Batch_id"),
                        rs.getInt("crate_id"),
                        rs.getString("Arrival_date"),
                        rs.getInt("Quantities")
                    };
                    model.addRow(row);
                }
            }
        }
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Table 2 Database Error: " + e.getMessage());
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Table 2 Structural Error: " + e.getMessage());
    }
    
    // 4. Update the UI specifically for jTable2
    jTable2.setModel(model);
    }

